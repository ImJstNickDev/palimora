// Diagnostic only: capture the authoritative query, mutate copies, never product code.
const assert = require("node:assert/strict"),
  fs = require("node:fs"),
  crypto = require("node:crypto");
const { spawn, execFileSync } = require("node:child_process");
const { once } = require("node:events");
assert.ok(new URL(process.env.DATABASE_URL).pathname.endsWith("_test"));
const { pool, transaction } = require("../apps/api/dist/db");
const search = require("../apps/api/dist/catalog-search");
const pause = (ms) => new Promise((r) => setTimeout(r, ms));
const base = "http://opensearch:9200";
const children = [];
function child(file, profile, extra = {}) {
  const fd = fs.openSync("/results/" + profile + ".log", "w");
  const c = spawn(process.execPath, [file], {
    stdio: ["ignore", fd, fd],
    env: {
      ...process.env,
      PROJECTION_MODE: "isolated",
      P0_PROFILE: "/results/" + profile + ".json",
      NODE_OPTIONS:
        "--require=/app/scripts/performance-p2d.cjs --require=/app/scripts/performance-search-spans.cjs",
      ...extra,
    },
  });
  fs.closeSync(fd);
  children.push(c);
  return c;
}
async function request(path, body, method = "POST") {
  const start = performance.now();
  const r = await fetch(base + path, {
    method,
    headers: { "content-type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
    signal: AbortSignal.timeout(30000),
  });
  const text = await r.text();
  assert.ok(r.ok, `${method} ${path}: ${r.status}`);
  return {
    value: JSON.parse(text),
    ms: performance.now() - start,
    bytes: Buffer.byteLength(text),
  };
}
async function pending() {
  return +(await pool.query("SELECT count(*) FROM catalog_text_pending"))
    .rows[0].count;
}
async function drain() {
  const deadline = Date.now() + 180000;
  while (await pending()) {
    assert.ok(Date.now() < deadline, "Drain timeout");
    await pause(100);
  }
}
async function stats() {
  const r = await request(
    "/_nodes/stats/indices,jvm,process,thread_pool",
    undefined,
    "GET",
  );
  return Object.values(r.value.nodes)[0];
}
const hash = (x) =>
  crypto.createHash("sha256").update(JSON.stringify(x)).digest("hex");
let captured;
(async () => {
  assert.equal(await pending(), 0);
  assert.equal(
    +(await pool.query("SELECT count(*) FROM catalog_documents")).rows[0].count,
    11032,
  );
  // Capture the exact request generated by the unchanged builder for /works defaults.
  const original = global.fetch;
  global.fetch = async (...args) => {
    if (String(args[0]).endsWith("/_search"))
      captured = JSON.parse(args[1].body);
    return original(...args);
  };
  let page;
  try {
    page = await transaction((db) => search.searchWorks(db, {}));
  } finally {
    global.fetch = original;
  }
  assert.ok(captured && page.next);
  assert.equal(Object.keys(captured.aggs).length, 10);
  await request(
    "/_search/point_in_time",
    { pit_id: [captured.pit.id] },
    "DELETE",
  );
  delete captured.pit;
  fs.writeFileSync(
    "/results/query-shape.json",
    JSON.stringify({
      hash: hash(captured),
      keys: Object.keys(captured),
      aggregations: Object.keys(captured.aggs),
      sort: captured.sort,
      track_total_hits: captured.track_total_hits,
    }),
  );
  child("apps/api/dist/main.js", "ablation-api");
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch("http://localhost:3000/api/v1/health")).ok) break;
    } catch {}
    await pause(1000);
  }
  // Preserve the original authenticated probe and its correlated preload as a control.
  execFileSync(process.execPath, ["scripts/benchmark-performance-http.cjs"], {
    stdio: "ignore",
  });
  fs.renameSync("/results/http-latency.json", "/results/http-control.json");
  await pool.query(
    "UPDATE operations_index SET paused=true WHERE kind='search'",
  );
  child("apps/api/dist/projection-worker.js", "ablation-projection");
  const variants = [
    "full-retain",
    "no-aggs",
    "no-total",
    "simple-sort",
    "full-close",
    "full-reuse",
  ];
  if (process.env.P2E_ORDER === "reverse") variants.reverse();
  const results = [];
  for (const condition of ["idle", "backlog"])
    for (const variant of variants) {
      await drain();
      await pool.query(
        "UPDATE operations_index SET paused=true WHERE kind='search'",
      );
      if (condition === "backlog")
        await pool.query(
          "INSERT INTO catalog_text_pending(work_id) SELECT work_id FROM catalog_documents ORDER BY work_id LIMIT 2000 ON CONFLICT DO NOTHING",
        );
      const before = await stats(),
        queueBefore = await pending(),
        started = Date.now();
      await pool.query(
        "UPDATE operations_index SET paused=false WHERE kind='search'",
      );
      const pits = [],
        samples = [],
        contextSamples = [];
      let shared;
      for (let i = 0; i < 103; i++) {
        let createMs = 0;
        if (!shared || variant !== "full-reuse") {
          const r = await request(
            "/" + search.SEARCH_INDEX + "/_search/point_in_time?keep_alive=5m",
          );
          shared = r.value.pit_id;
          pits.push(shared);
          createMs = r.ms;
        }
        const query = structuredClone(captured);
        query.pit = { id: shared, keep_alive: "5m" };
        if (variant === "no-aggs") delete query.aggs;
        if (variant === "no-total") query.track_total_hits = false;
        if (variant === "simple-sort") query.sort = [{ id: "asc" }];
        const r = await request("/_search", query);
        let closeMs = 0;
        if (variant === "full-close") {
          const c = await request(
            "/_search/point_in_time",
            { pit_id: [shared] },
            "DELETE",
          );
          closeMs = c.ms;
        }
        samples.push({
          warmup: i < 3,
          client_ms: r.ms,
          took_ms: r.value.took,
          create_ms: createMs,
          close_ms: closeMs,
          response_bytes: r.bytes,
          hits: r.value.hits.hits.length,
          total: r.value.hits.total ?? null,
          ids_hash: hash(r.value.hits.hits.map((h) => h._id)),
          sort_hash: hash(r.value.hits.hits.map((h) => h.sort)),
        });
        if (i % 20 === 0 || i === 102) {
          const s = await stats();
          contextSamples.push({
            request: i,
            time: Date.now(),
            pending: await pending(),
            open_contexts: s.indices.search.open_contexts,
            segments: s.indices.segments,
            heap: s.jvm.mem.heap_used_in_bytes,
          });
        }
      }
      const queryEnded = Date.now(),
        queueAfter = await pending(),
        after = await stats();
      let cleanup = null;
      if (variant !== "full-close")
        cleanup = (
          await request("/_search/point_in_time", { pit_id: pits }, "DELETE")
        ).ms;
      const afterClose = await stats();
      results.push({
        condition,
        variant,
        started,
        queryEnded,
        queueBefore,
        queueAfter,
        indexed_during_window: queueBefore - queueAfter,
        indexed_per_second:
          (queueBefore - queueAfter) / ((queryEnded - started) / 1000),
        created: pits.length,
        cleanup_ms: cleanup,
        before,
        after,
        afterClose,
        contextSamples,
        samples,
      });
      fs.writeFileSync(
        "/results/ablations.json",
        JSON.stringify(
          { order: process.env.P2E_ORDER, query_hash: hash(captured), results },
          null,
          2,
        ),
      );
      await drain();
    }
  assert.equal(await pending(), 0);
  await request("/" + search.SEARCH_INDEX + "/_refresh");
  assert.equal(
    (await request("/" + search.SEARCH_INDEX + "/_count", undefined, "GET"))
      .value.count,
    11032,
  );
  fs.writeFileSync(
    "/results/ablation-verification.json",
    JSON.stringify({ documents: 11032, queues_drained: true }),
  );
})()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(async () => {
    for (const c of children.reverse()) {
      if (c.exitCode === null && c.signalCode === null) {
        c.kill("SIGTERM");
        const timer = setTimeout(() => c.kill("SIGKILL"), 30000);
        await once(c, "exit");
        clearTimeout(timer);
      }
    }
    await pool.end();
  });
